-- Esquema de referência para o Orçamento Financeiro Pessoal.
-- Execute somente se estas tabelas ainda não existirem ou após revisar seu esquema atual.
create table if not exists public.incomes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  description text not null,
  type text not null,
  amount numeric(12,2) not null check (amount >= 0),
  date date not null,
  created_at timestamptz not null default now()
);

create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  description text not null,
  category text not null,
  amount numeric(12,2) not null check (amount >= 0),
  status text not null default 'Em Aberto',
  date date not null,
  created_at timestamptz not null default now()
);

create table if not exists public.debts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  creditor text not null,
  type text not null,
  original_amount numeric(12,2) not null default 0 check (original_amount >= 0),
  amount numeric(12,2) not null default 0 check (amount >= 0),
  interest_rate numeric(8,3) not null default 0 check (interest_rate >= 0),
  installments text,
  status text not null default 'Em Aberto',
  priority text not null default 'Média',
  created_at timestamptz not null default now()
);

create table if not exists public.emergency_fund (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  current_amount numeric(12,2) not null default 0 check (current_amount >= 0),
  target_months integer not null default 6 check (target_months in (3,6,12)),
  manual_expense numeric(12,2) not null default 0 check (manual_expense >= 0),
  updated_at timestamptz not null default now()
);

alter table public.incomes enable row level security;
alter table public.expenses enable row level security;
alter table public.debts enable row level security;
alter table public.emergency_fund enable row level security;

drop policy if exists "incomes own rows" on public.incomes;
create policy "incomes own rows" on public.incomes
  for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "expenses own rows" on public.expenses;
create policy "expenses own rows" on public.expenses
  for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "debts own rows" on public.debts;
create policy "debts own rows" on public.debts
  for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "emergency fund own row" on public.emergency_fund;
create policy "emergency fund own row" on public.emergency_fund
  for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

grant select, insert, update, delete on public.incomes, public.expenses, public.debts, public.emergency_fund to authenticated;
grant usage, select on all sequences in schema public to authenticated;
